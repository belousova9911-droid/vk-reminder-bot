def run_scheduler():
    """Все напоминания по Перми (без pytz)"""
    schedule.every().day.at("09:00").do(send_morning)
    schedule.every().day.at("11:30").do(send_by_time, "11:30")
    schedule.every().day.at("12:00").do(send_by_time, "12:00")
    schedule.every().day.at("14:30").do(send_by_time, "14:30")

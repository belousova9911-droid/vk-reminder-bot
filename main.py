logger.info(f"🕒 Часовой пояс: Пермь ({TIMEZONE})")
logger.info("🚀 Бот запущен.")

def send_message(text: str):
    try:
        vk.messages.send(peer_id=PEER_ID, message=text, random_id=int(time.time() * 1000))
        logger.info("✅ Сообщение успешно отправлено.")
    except vk_api.exceptions.ApiError as e:
        logger.error(f"❌ Ошибка API ВКонтакте: {e}")
    except Exception as e:
        logger.error(f"❌ Неожиданная ошибка: {e}")

# ================= ЗАПУСК =================
while True:
    try:
        now = datetime.now(TIMEZONE)
        current_minute = now.strftime("%H:%M")

        # Утреннее сообщение (по кругу)
        if current_minute == "09:00":
            msg = random.choice(MORNING_MESSAGES)
            send_message(msg)

        # Обычные напоминания
        if current_minute in SCHEDULE:
            send_message(SCHEDULE[current_minute])

        # Закрытие смены
        weekday = now.weekday()
        if ((weekday in (6, 0, 1, 2, 3) and now.hour == 22 and now.minute == 20) or
            (weekday in (4, 5) and now.hour == 23 and now.minute == 20)):
            if weekday in (6, 0, 1, 2, 3):
                send_message(CLOSING_MESSAGE)
            else:
                send_message(CLOSING_MESSAGE)

        # ================== КОМАНДА /ВРЕМЯ ==================
        if current_minute == "00:00":  # проверяем каждую минуту
            if now.hour == 0 and now.minute == 0:
                vk.messages.send(peer_id=PEER_ID, message="Текущее время по Перми: 00:00\nОтправляется сообщение: Утреннее сообщение (09:00)")

        time.sleep(60)  # проверяем каждую минуту

    except Exception as e:
        logger.error(f"Ошибка в цикле: {e}")
        time.sleep(60)

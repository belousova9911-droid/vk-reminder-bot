# ================== ИНИЦИАЛИЗАЦИЯ ==================
vk_session = vk_api.VkApi(token=TOKEN)
vk = vk_session.get_api()
longpoll = VkBotLongPoll(vk_session, GROUP_ID)

def send_message(text: str):
    now = datetime.now(PERM_TZ)
    try:
        vk.messages.send(
            peer_id=PEER_ID,
            message=text,
            random_id=0
        )
        print(f"[{now.strftime('%H:%M:%S')} Пермь] Сообщение отправлено")
    except Exception as e:
        print(f"[{now.strftime('%H:%M:%S')} Пермь] Ошибка отправки: {e}")

def send_by_time(time_str: str):
    text = MESSAGES.get(time_str)
    if text:
        send_message(text)

def send_morning():
    now = datetime.now(PERM_TZ)
    day_of_year = now.timetuple().tm_yday
    message = MORNING_MESSAGES[day_of_year % len(MORNING_MESSAGES)]
    send_message(message)

def send_closing():
    now = datetime.now(PERM_TZ)
    weekday = now.weekday()
    is_weekday = weekday in (6, 0, 1, 2, 3)
    is_weekend = weekday in (4, 5)

    if now.hour == 22 and now.minute == 20 and is_weekday:
        send_message(CLOSING_MESSAGE)
    elif now.hour == 23 and now.minute == 20 and is_weekend:
        send_message(CLOSING_MESSAGE)


# ================== ИНИЦИАЛИЗАЦИЯ ==================
vk_session = vk_api.VkApi(token=TOKEN)
vk = vk_session.get_api()
longpoll = VkBotLongPoll(vk_session, GROUP_ID)

def send_message(text: str):
    """Отправка сообщения в чат"""
    now = datetime.now(PERM_TZ)
    try:
        vk.messages.send(
            peer_id=PEER_ID,
            message=text,
            random_id=0
        )
        print(f"[{now.strftime('%H:%M:%S')} Пермь] Сообщение отправлено")
    except Exception as e:
        print(f"[{now.strftime('%H:%M:%S')} Пермь] Ошибка отправки: {e}")

def send_by_time(time_str: str):
    """Отправка обычного напоминания"""
    text = MESSAGES.get(time_str)
    if text:
        send_message(text)

def send_closing():
    """Отправка сообщения о закрытии смены (с учётом будни/выходные)"""
    now = datetime.now(PERM_TZ)
    weekday = now.weekday()  # 0 = понедельник, 6 = воскресенье

    # 22:20 — только в будни (пн–пт)
    if now.hour == 22 and now.minute == 20 and weekday < 5:
        send_message(CLOSING_MESSAGE)

    # 23:20 — только в выходные (сб–вс)
    elif now.hour == 23 and now.minute == 20 and weekday >= 5:
        send_message(CLOSING_MESSAGE)

def run_scheduler():
    """Настройка и запуск всех напоминаний"""
    # Обычные напоминания
    for time_str in MESSAGES.keys():
        schedule.every().day.at(time_str).do(send_by_time, time_str)

    # Закрытие смены
    schedule.every().day.at("22:20").do(send_closing)
    schedule.every().day.at("23:20").do(send_closing)

    print("Все напоминания зарегистрированы")

    while True:
        schedule.run_pending()
        time.sleep(20)  # проверяем каждые 20 секунд

# ================== ЗАПУСК ==================
print("Бот запускается...")
print(f"Текущее время по Перми: {datetime.now(PERM_TZ).strftime('%d.%m.%Y %H:%M:%S')}")

scheduler_thread = threading.Thread(target=run_scheduler, daemon=True)
scheduler_thread.start()

print("Планировщик запущен. Long Poll слушает...")

